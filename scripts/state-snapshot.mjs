#!/usr/bin/env node
/**
 * Dump the DB-held operational state that a rebuilt install cannot derive
 * from the repo: scheduled_tasks (full prompts/scripts) and registered_groups
 * (full container_config, incl. the program-repo rw mount JSON).
 *
 * Why: task prompts and group registrations can exist ONLY in the live DB
 * (a rebuild then registers stale prompts and monitors silently report
 * nothing). This dump, committed
 * to the repo on a schedule, is the rebuild source of truth AND a drift log:
 * any live prompt edit shows up as a git diff on the next snapshot.
 *
 * Runs ON the VPS with the app's own node_modules:
 *   node /opt/programos/scripts/state-snapshot.mjs
 * Prints one deterministic JSON document to stdout (sorted keys/rows, no
 * timestamps inside — the committing snapshot's git history is the clock, and
 * an embedded timestamp would make every run a diff even when nothing
 * changed). Consumed by scripts/state-snapshot-pull.sh (Mac-side cron), which
 * commits it as ops/state-snapshot/db-state.json.
 */
import Database from 'better-sqlite3';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { assertSafeDbFile } from './safe-artifact.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dbPath = process.argv[2] || path.join(repoRoot, 'store', 'messages.db');

// store/ is writable for the main group: never follow a planted link to
// another database (this output is committed to the repo).
assertSafeDbFile(dbPath);
const db = new Database(dbPath, { readonly: true, fileMustExist: true });

function coerceTaskText(value) {
  if (value === null || value === undefined) return null;
  if (typeof value === 'string') return value;
  if (Buffer.isBuffer(value)) return value.toString('utf-8');
  if (
    value &&
    typeof value === 'object' &&
    value.type === 'Buffer' &&
    Array.isArray(value.data)
  ) {
    try {
      return Buffer.from(value.data).toString('utf-8');
    } catch {
      // fall through to generic string coercion
    }
  }
  return String(value);
}

/** Rows with stable column order and stable row order for clean diffs. */
function dump(table, orderBy, volatileColumns) {
  const rows = db.prepare(`SELECT * FROM ${table} ORDER BY ${orderBy}`).all();
  return rows.map((row) => {
    const out = {};
    for (const key of Object.keys(row).sort()) {
      // Volatile run-state columns (next_run/last_run/last_result) change on
      // every scheduler tick; including them would bury real prompt/config
      // diffs in noise. They are runtime state, not rebuild state.
      if (volatileColumns.includes(key)) continue;
      if (key === 'prompt') {
        out[key] = coerceTaskText(row[key]) ?? '';
      } else if (key === 'script') {
        out[key] = coerceTaskText(row[key]);
      } else {
        out[key] = row[key];
      }
    }
    return out;
  });
}

const snapshot = {
  _readme:
    'Rebuild source of truth for DB-only state. Generated by scripts/state-snapshot.mjs on the VPS, committed by scripts/state-snapshot-pull.sh (Mac cron). Volatile columns (next_run/last_run/last_result) are excluded by design. To restore: re-INSERT these rows into store/messages.db on the new host, then verify against docs/reminder-registry.md.',
  scheduled_tasks: dump('scheduled_tasks', 'id', [
    'next_run',
    'last_run',
    'last_result',
  ]),
  registered_groups: dump('registered_groups', 'jid', []),
};

process.stdout.write(JSON.stringify(snapshot, null, 2) + '\n');
