/**
 * Credential proxy for container isolation.
 * Containers connect here instead of directly to the Anthropic API.
 * The proxy injects real credentials so containers never see them.
 *
 * Two auth modes:
 *   API key:  Proxy injects x-api-key on every request.
 *   OAuth:    Container CLI exchanges its placeholder token for a temp
 *             API key via /api/oauth/claude_cli/create_api_key.
 *             Proxy injects real OAuth token on that exchange request;
 *             subsequent requests carry the temp key which is valid as-is.
 *
 * Each run's token is registered with a provider. The proxy picks the
 * upstream and the credential per request from that token, and reports each
 * upstream result to the provider's circuit breaker (model-provider.ts).
 */
import { createServer, Server } from 'http';
import { request as httpsRequest } from 'https';
import { request as httpRequest, RequestOptions } from 'http';
import { timingSafeEqual } from 'crypto';

import { readEnvFile } from './env.js';
import { logger } from './logger.js';
import {
  basePath,
  getModelProviderConfig,
  ModelProvider,
  recordProviderResult,
} from './model-provider.js';
import { checkProxyRequest, webToolsEnabled } from './web-tools.js';

export type AuthMode = 'api-key' | 'oauth';

export interface ProxyConfig {
  authMode: AuthMode;
}

const PROXY_TOKEN_HEADER = 'x-nanoclaw-proxy-token';
const MAX_PROXY_BODY_BYTES = 20 * 1024 * 1024;
const activeCallers = new Map<string, ModelProvider>();
/**
 * The token may also arrive as a path prefix. It is not verified that the
 * SDK sends ANTHROPIC_CUSTOM_HEADERS in Foundry mode, and a request with no
 * token is rejected. A path with this prefix must never be logged.
 */
const PATH_TOKEN_RE = /^\/_t\/([0-9a-f]{64})(\/.*)?$/;

/** One log line per key for the life of the process, with a cap on keys. */
const warned = new Set<string>();
function warnOnce(key: string, fields: object, message: string): void {
  if (warned.has(key) || warned.size >= 200) return;
  warned.add(key);
  logger.warn(fields, message);
}

/** Tokens are generated by the host for one container run, never persisted. */
export function registerProxyCaller(
  token: string,
  provider: ModelProvider = 'anthropic',
): void {
  if (!/^[0-9a-f]{64}$/.test(token))
    throw new Error('Invalid proxy caller token');
  activeCallers.set(token, provider);
}

export function revokeProxyCaller(token: string): void {
  activeCallers.delete(token);
}

function providerForToken(
  token: string | string[] | undefined,
): ModelProvider | null {
  if (typeof token !== 'string' || !/^[0-9a-f]{64}$/.test(token)) return null;
  const candidate = Buffer.from(token, 'hex');
  let found: ModelProvider | null = null;
  for (const [active, provider] of activeCallers) {
    if (timingSafeEqual(candidate, Buffer.from(active, 'hex')))
      found = provider;
  }
  return found;
}

/**
 * Identify the caller from the token header, or else from a path prefix.
 * Returns the provider and the path with any token prefix removed.
 */
function resolveCaller(
  headerToken: string | string[] | undefined,
  url: string,
): { provider: ModelProvider; path: string } | null {
  const match = PATH_TOKEN_RE.exec(url);
  const path = match ? match[2] || '/' : url;
  const provider =
    providerForToken(headerToken) ?? (match && providerForToken(match[1]));
  return provider ? { provider, path } : null;
}

export function startCredentialProxy(
  port: number,
  host = '127.0.0.1',
): Promise<Server> {
  const secrets = readEnvFile([
    'ANTHROPIC_API_KEY',
    'CLAUDE_CODE_OAUTH_TOKEN',
    'ANTHROPIC_AUTH_TOKEN',
    'ANTHROPIC_BASE_URL',
  ]);

  const oauthToken =
    secrets.CLAUDE_CODE_OAUTH_TOKEN || secrets.ANTHROPIC_AUTH_TOKEN;
  // OAuth (subscription) wins when both are configured: agent containers bill
  // to the subscription, while ANTHROPIC_API_KEY stays available for the
  // behaviour sensor's direct Messages API calls (OAuth tokens can't call it).
  const authMode: AuthMode = oauthToken ? 'oauth' : 'api-key';

  const upstreamUrl = new URL(
    secrets.ANTHROPIC_BASE_URL || 'https://api.anthropic.com',
  );
  // A path in ANTHROPIC_BASE_URL is kept: it is joined before the request
  // path. No path (the default) leaves the request path as sent.
  const anthropicPrefix = basePath(upstreamUrl);
  // Throws on a listed provider with missing settings: a startup error.
  const foundry = getModelProviderConfig().foundry;
  // Read once at start: changing AGENT_WEB_TOOLS needs a restart.
  const webTools = webToolsEnabled();

  return new Promise((resolve, reject) => {
    const server = createServer((req, res) => {
      const caller = resolveCaller(
        req.headers[PROXY_TOKEN_HEADER],
        req.url || '/',
      );
      if (!caller) {
        res.writeHead(401);
        res.end('Unauthorized');
        req.resume();
        return;
      }
      const { provider, path: requestPath } = caller;
      if (provider === 'foundry' && !foundry) {
        // Not reachable through selectProvider(); refuse instead of
        // sending a Foundry-shaped request to another upstream.
        res.writeHead(502);
        res.end('Bad Gateway');
        req.resume();
        return;
      }
      const targetUrl =
        provider === 'foundry' && foundry ? foundry.baseUrl : upstreamUrl;
      const isHttps = targetUrl.protocol === 'https:';
      const makeRequest = isHttps ? httpsRequest : httpRequest;

      const rejectOversize = () => {
        res.writeHead(413);
        res.end('Payload Too Large');
        req.resume();
      };
      if (Number(req.headers['content-length']) > MAX_PROXY_BODY_BYTES) {
        rejectOversize();
        return;
      }
      const chunks: Buffer[] = [];
      let bodySize = 0;
      let tooLarge = false;
      req.on('data', (c: Buffer) => {
        if (tooLarge) return;
        bodySize += c.length;
        if (bodySize > MAX_PROXY_BODY_BYTES) {
          tooLarge = true;
          chunks.length = 0;
          rejectOversize();
          return;
        }
        chunks.push(c);
      });
      req.on('end', () => {
        if (tooLarge) return;
        let body: Buffer = Buffer.concat(chunks);
        // Web tools off (AGENT_WEB_TOOLS): refuse a request that would make
        // the provider contact an outside host. Both providers pass here.
        // See checkProxyRequest in src/web-tools.ts.
        if (!webTools) {
          const verdict = checkProxyRequest({
            path: requestPath,
            contentEncoding: req.headers['content-encoding'],
            body,
          });
          if (!verdict.allow) {
            // The reason is fixed text. The path is not logged: it may be
            // caller-chosen text, and may hold the token prefix.
            logger.warn(
              { provider, reason: verdict.reason },
              'Credential proxy refused a request (AGENT_WEB_TOOLS is off)',
            );
            res.writeHead(403, { 'content-type': 'application/json' });
            res.end(
              JSON.stringify({
                type: 'error',
                error: {
                  type: 'permission_error',
                  message: `Refused by this deployment (web tools are off): ${verdict.reason}.`,
                },
              }),
            );
            return;
          }
          body = verdict.body;
          for (const type of verdict.unknownToolTypes)
            warnOnce(
              `tool:${type}`,
              { provider, toolType: type },
              'Credential proxy forwarded a tool type it does not know while AGENT_WEB_TOOLS is off; check that it does not reach outside hosts',
            );
          if (verdict.otherPath) {
            const pathClass = requestPath
              .split('?')[0]
              .split('/')
              .slice(0, 4)
              .join('/');
            warnOnce(
              `path:${pathClass}`,
              { provider, pathClass },
              'Credential proxy forwarded a request that is not a model request (logged once per path)',
            );
          }
        }
        const headers: Record<string, string | number | string[] | undefined> =
          {
            ...(req.headers as Record<string, string>),
            host: targetUrl.host,
            'content-length': body.length,
          };

        // Strip hop-by-hop headers that must not be forwarded by proxies
        delete headers['connection'];
        delete headers['keep-alive'];
        delete headers['transfer-encoding'];
        delete headers[PROXY_TOKEN_HEADER];

        if (provider === 'foundry' && foundry) {
          // The real key goes in whichever key header the caller used. A
          // bearer token from the container is never forwarded.
          delete headers['authorization'];
          const sent = ['x-api-key', 'api-key'].filter((h) => headers[h]);
          for (const h of sent.length ? sent : [foundry.keyHeader])
            headers[h] = foundry.apiKey;
        } else if (authMode === 'api-key') {
          // API key mode: inject x-api-key on every request
          delete headers['x-api-key'];
          headers['x-api-key'] = secrets.ANTHROPIC_API_KEY;
        } else {
          // OAuth mode: replace placeholder Bearer token with the real one
          // only when the container actually sends an Authorization header
          // (exchange request + auth probes). Post-exchange requests use
          // x-api-key only, so they pass through without token injection.
          if (headers['authorization']) {
            delete headers['authorization'];
            if (oauthToken) {
              headers['authorization'] = `Bearer ${oauthToken}`;
            }
          }
        }

        const upstream = makeRequest(
          {
            hostname: targetUrl.hostname,
            port: targetUrl.port || (isHttps ? 443 : 80),
            // Foundry: the path as sent (the container's base URL already
            // carries the Foundry path part).
            path:
              provider === 'foundry'
                ? requestPath
                : anthropicPrefix + requestPath,
            method: req.method,
            headers,
          } as RequestOptions,
          (upRes) => {
            recordProviderResult(provider, { status: upRes.statusCode });
            res.writeHead(upRes.statusCode!, upRes.headers);
            upRes.pipe(res);
          },
        );

        upstream.on('error', (err) => {
          recordProviderResult(provider, { networkError: true });
          logger.error(
            { err, url: requestPath, provider },
            'Credential proxy upstream error',
          );
          if (!res.headersSent) {
            res.writeHead(502);
            res.end('Bad Gateway');
          }
        });

        upstream.write(body);
        upstream.end();
      });
    });

    server.listen(port, host, () => {
      logger.info({ port, host, authMode }, 'Credential proxy started');
      resolve(server);
    });

    server.on('error', reject);
  });
}

/** Detect which auth mode the host is configured for. OAuth wins when both
 * are present (must mirror startCredentialProxy's precedence). */
export function detectAuthMode(): AuthMode {
  const secrets = readEnvFile([
    'ANTHROPIC_API_KEY',
    'CLAUDE_CODE_OAUTH_TOKEN',
    'ANTHROPIC_AUTH_TOKEN',
  ]);
  const hasOauth =
    secrets.CLAUDE_CODE_OAUTH_TOKEN || secrets.ANTHROPIC_AUTH_TOKEN;
  return hasOauth ? 'oauth' : 'api-key';
}
